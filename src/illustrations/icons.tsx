function paint(p: ArtPalette, tone: Tone): string {
  const dot = tone.indexOf('.');
  if (dot < 0) return p[tone as 'line' | 'paper' | 'window' | 'text' | 'shadow'];
  return p[tone.slice(0, dot) as ArtHue | 'neutral' | 'dark'][tone.slice(dot + 1) as Face];
}

/** A small isometric object for a feature tile. Draws no tile of its own; the caller supplies it. */
export function FeatureIcon({ name, size = 48 }: { name: FeatureIconName; size?: number }) {
  const p = useArtPalette();
  // Hidden from screen readers on a View: react-native-svg passes these props straight to <svg> on the web.
  return (
    <View accessibilityElementsHidden importantForAccessibility="no-hide-descendants" style={{ width: size, height: size }}>
      <Svg width={size} height={size} viewBox="0 0 64 64">
        {ICONS[name].map(([tone, d, width], i) => {
          const color = paint(p, tone);
          if (width === undefined) return <Path key={i} d={d} fill={color} stroke={p.line} strokeWidth={STROKE} strokeLinejoin="round" />;
          if (width === 0) return <Path key={i} d={d} fill={color} />;
          return <Path key={i} d={d} fill="none" stroke={color} strokeWidth={width} strokeLinecap="round" strokeLinejoin="round" />;
        })}
      </Svg>
    </View>
  );
}
