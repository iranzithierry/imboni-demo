function history(base: number, drift: number, n: number): number[] {
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = i - (n - 1);
    out.push(base * (1 + drift * t) + Math.sin(i * 1.7) * base * 0.0012 + Math.cos(i * 0.6) * base * 0.0008);
  }
  out[n - 1] = base;
  return out.map((v) => Math.max(v, base * 0.5));
}

